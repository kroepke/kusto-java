    // PORT: §4 string.IsNullOrWhiteSpace / string.IsNullOrEmpty
    static boolean isNullOrWhiteSpace(String s) {
        return s == null || s.isBlank();
    }

    static boolean isNullOrEmpty(String s) {
        return s == null || s.isEmpty();
    }

    // PORT: §4 string.Format composite formatting ({0}, {1}, "{{", "}}"); only what the generator uses.
    static String format(String format, Object... args) {
        var sb = new StringBuilder(format.length() + 16);
        int i = 0;
        int n = format.length();
        while (i < n) {
            char c = format.charAt(i);
            if (c == '{') {
                if (i + 1 < n && format.charAt(i + 1) == '{') {
                    sb.append('{');
                    i += 2;
                    continue;
                }
                int close = format.indexOf('}', i);
                if (close < 0) {
                    throw new IllegalArgumentException("Input string was not in a correct format."); // PORT: §3.16 FormatException
                }
                int index = Integer.parseInt(format.substring(i + 1, close).trim());
                if (index < 0 || index >= args.length) {
                    throw new IllegalArgumentException("Index (zero based) must be greater than or equal to zero and less than the size of the argument list."); // PORT: §3.16 FormatException
                }
                sb.append(args[index] == null ? "" : String.valueOf(args[index]));
                i = close + 1;
            } else if (c == '}') {
                if (i + 1 < n && format.charAt(i + 1) == '}') {
                    sb.append('}');
                    i += 2;
                    continue;
                }
                throw new IllegalArgumentException("Input string was not in a correct format."); // PORT: §3.16 FormatException
            } else {
                sb.append(c);
                i++;
            }
        }
        return sb.toString();
    }

    // PORT: §4 Javadoc must not contain HTML metacharacters, "*/", "@" tags or unicode escapes from data.
    static String escapeJavadoc(String text) {
        var sb = new StringBuilder(text.length());
        for (int i = 0; i < text.length(); i++) {
            char c = text.charAt(i);
            switch (c) {
                case '&': sb.append("&amp;"); break;
                case '<': sb.append("&lt;"); break;
                case '>': sb.append("&gt;"); break;
                case '@': sb.append("&#64;"); break;
                case '\\': sb.append("&#92;"); break;
                case '/':
                    sb.append(i > 0 && text.charAt(i - 1) == '*' ? "&#47;" : "/");
                    break;
                default: sb.append(c);
            }
        }
        return sb.toString();
    }
