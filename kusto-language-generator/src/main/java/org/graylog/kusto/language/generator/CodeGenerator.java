    /**
     * Given a compoundName/CompoundName, returns the corresponding PascalCase
     * version of the name (CompoundName).
     */
    public static String getPascalCase(String name) {
        if (isNullOrWhiteSpace(name)) {
            return name;
        }
        var first = Character.toUpperCase(name.charAt(0));
        if (name.length() == 1) {
            return String.valueOf(first);
        }
        return first + name.substring(1);
    }

    /**
     * Given a compoundName/CompoundName, returns the corresponding CamelCase
     * version of the name (compoundName).
     */
    public static String getCamelCase(String name) {
        if (isNullOrWhiteSpace(name)) {
            return name;
        }
        var first = Character.toLowerCase(name.charAt(0));
        if (name.length() == 1) {
            return String.valueOf(first);
        }
        var ret = first + name.substring(1);
        if (ret.equals("operator")) { // Add here all C# keywords people dream up
            return "@" + ret;
        }
        return ret;
    }

    // PORT: §4 Java-flavoured equivalent of GetCamelCase: escapes Java reserved words with a trailing
    // underscore (PORTING.md 2.3) instead of C# keywords with '@' ("operator" is a legal Java name).
    public static String getJavaCamelCase(String name) {
        if (isNullOrWhiteSpace(name)) {
            return name;
        }
        var ret = Character.toLowerCase(name.charAt(0)) + name.substring(1);
        return JAVA_RESERVED.contains(ret) ? ret + "_" : ret;
    }

